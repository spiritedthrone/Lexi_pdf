"""PDF Generation Service for downloadable simplified documents using ReportLab."""

import io
from typing import Dict, Any, List
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """Custom canvas that adds page numbers and running footer."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748B"))

        # Footer divider line
        self.setLineWidth(0.5)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.line(54, 40, 558, 40)

        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 25, page_text)
        self.drawString(54, 25, "PDF Summarizer — Rewritten Output")
        self.restoreState()


def create_simplified_pdf(filename: str, full_text: str, chunks: List[Dict[str, Any]] = None) -> bytes:
    """
    Generates a properly formatted PDF document preserving page order, chapters, and headings.
    """
    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        leading=28,
        textColor=colors.HexColor("#1E293B"),
        spaceAfter=12,
    )

    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748B"),
        spaceAfter=20,
    )

    h2_style = ParagraphStyle(
        'DocH2',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=15,
        leading=19,
        textColor=colors.HexColor("#334155"),
        spaceBefore=16,
        spaceAfter=8,
        keepWithNext=True,
    )

    h3_style = ParagraphStyle(
        'DocH3',
        parent=styles['Heading3'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#475569"),
        spaceBefore=12,
        spaceAfter=6,
        keepWithNext=True,
    )

    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['BodyText'],
        fontName='Helvetica',
        fontSize=10.5,
        leading=16,
        textColor=colors.HexColor("#1E293B"),
        spaceAfter=10,
    )

    story = []

    # Document Header Title
    clean_title = filename.rsplit('.', 1)[0].replace('_', ' ').replace('-', ' ').title()
    story.append(Paragraph(f"Simplified: {clean_title}", title_style))
    story.append(Paragraph("Generated by PDF Summarizer", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceAfter=15))

    # Process text content line by line preserving structure
    paragraphs = full_text.split("\n\n")

    for paragraph in paragraphs:
        p_text = paragraph.strip()
        if not p_text:
            continue

        if p_text.startswith("## "):
            story.append(Paragraph(p_text[3:].strip(), h2_style))
        elif p_text.startswith("### "):
            story.append(Paragraph(p_text[4:].strip(), h3_style))
        elif p_text.startswith("# "):
            story.append(Paragraph(p_text[2:].strip(), title_style))
        else:
            # Replace single newlines within paragraph with spaces
            inline_cleaned = " ".join(line.strip() for line in p_text.split("\n"))
            story.append(Paragraph(inline_cleaned, body_style))

    doc.build(story, canvasmaker=NumberedCanvas)

    pdf_data = buffer.getvalue()
    buffer.close()
    return pdf_data
